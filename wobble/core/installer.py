"""
Wobble Standalone Installer
Turns Wobble into a real, self-contained piece of software.

The classic ``git clone`` + symlink setup breaks the moment the checkout is
deleted. This installer instead copies the runtime into a private application
directory, precompiles bytecode, and writes a launcher that never references the
source checkout again.

Layout (defaults, override with ``WOBBLE_INSTALL_DIR``)::

    ~/.local/share/wobble/
        app/                 <- the installed runtime (self-contained)
            wob.py           <- bootstrap
            wobble/          <- Python package (+ __pycache__)
            LICENSE
        install.json         <- manifest: version, files, hashes, launchers
    ~/.local/bin/wob         <- generated POSIX-sh launcher
"""

import hashlib
import json
import os
import shlex
import shutil
import stat
import sys
import time
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

from wobble import __version__
from wobble.core.completions import COMPLETIONS
from wobble.core.context import get_home, get_prefix, is_termux
from wobble.core.fsutil import atomic_write_json, atomic_write_text

INSTALL_SCHEMA = 1
APP_DIRNAME = "app"
MANIFEST_NAME = "install.json"
LAUNCHER_NAME = "wob"
LAUNCHER_MARKER = "Wobble launcher (auto-generated by `wob self install`)"
COMPLETION_MARKER = "Wobble (wob)"
# Prevent installing onto top-level system folders or deleting them on uninstall.
_UNSAFE_ROOTS = {
    Path("/"), Path("/system"), Path("/data"), Path("/storage"), Path("/sdcard"),
}
_IGNORED_COPY = shutil.ignore_patterns(
    "__pycache__", "*.pyc", "*.pyo", "*.apk", ".git", ".github", ".wobble",
)


class InstallerError(RuntimeError):
    """Raised when an install/uninstall operation cannot be performed safely."""


# ---------------------------------------------------------------------------
# Paths & helpers
# ---------------------------------------------------------------------------
def running_install_root() -> Optional[Path]:
    """
    If this module is executing from an installed app directory
    (``<root>/app/wobble/core/installer.py``), return ``<root>``.

    This makes custom install locations work without exporting environment
    variables in every shell.
    """
    try:
        app_dir = Path(__file__).resolve().parents[2]
    except IndexError:
        return None
    if app_dir.name == APP_DIRNAME and (app_dir / "wob.py").is_file():
        return app_dir.parent
    return None


def default_install_root() -> Path:
    override = os.environ.get("WOBBLE_INSTALL_DIR")
    if override:
        return Path(override).expanduser()
    discovered = running_install_root()
    if discovered is not None:
        return discovered
    return get_home() / ".local" / "share" / "wobble"


def default_bin_dir() -> Path:
    override = os.environ.get("WOBBLE_BIN_DIR")
    if override:
        return Path(override).expanduser()
    return get_home() / ".local" / "bin"


def package_root() -> Path:
    """Return the repository root, or the installed app directory."""
    # wobble/core/installer.py -> repository (or installed app) root
    return Path(__file__).resolve().parents[2]


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(256 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _iter_files(root: Path) -> Iterable[Path]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != "__pycache__")
        for name in sorted(filenames):
            if name.endswith((".pyc", ".pyo")):
                continue
            yield Path(dirpath) / name


def _assert_safe_root(path: Path) -> None:
    if not path.is_absolute():
        raise InstallerError(f"Install location must be an absolute path: {path}")
    if path in _UNSAFE_ROOTS or path == get_home().resolve():
        raise InstallerError(f"Refusing to use unsafe install location: {path}")
    if len(path.parts) < 3:
        raise InstallerError(f"Refusing to use overly broad install location: {path}")


def _is_our_launcher(path: Path) -> bool:
    """Return True when *path* is a launcher this installer wrote."""
    try:
        if path.is_symlink():
            target = os.readlink(str(path))
            return "wobble" in target and target.rstrip("/").endswith("bin/wob")
        if path.is_file():
            text = path.read_text(encoding="utf-8", errors="ignore")[:4096]
            return LAUNCHER_MARKER in text
    except OSError:
        return False
    return False


def _launcher_script(app_dir: Path, python_fallback: str) -> str:
    app = shlex.quote(str(app_dir))
    fallback = shlex.quote(python_fallback)
    return f"""#!/usr/bin/env sh
# {LAUNCHER_MARKER}.
# This file is standalone: it only needs the installed app below and does not
# reference (or depend on) the source checkout Wobble was installed from.
APP={app}
if [ ! -f "$APP/wob.py" ]; then
    echo "wob: installation is damaged (missing $APP/wob.py)." >&2
    echo "wob: reinstall Wobble with: sh install.sh" >&2
    exit 127
fi
if [ -n "${{WOBBLE_PYTHON:-}}" ] && [ -x "${{WOBBLE_PYTHON}}" ]; then
    PY="$WOBBLE_PYTHON"
elif command -v python3 >/dev/null 2>&1; then
    PY=python3
elif command -v python >/dev/null 2>&1; then
    PY=python
elif [ -x {fallback} ]; then
    PY={fallback}
else
    echo "wob: Python 3 is required but was not found in PATH." >&2
    echo "wob: install it with: pkg install -y python" >&2
    exit 127
fi
exec "$PY" "$APP/wob.py" "$@"
"""


_BOOTSTRAP = '''#!/usr/bin/env python3
"""Wobble installed bootstrap (generated by the installer)."""

import os
import sys

APP_DIR = os.path.dirname(os.path.abspath(__file__))
if APP_DIR in sys.path:
    sys.path.remove(APP_DIR)
sys.path.insert(0, APP_DIR)

try:
    from wobble.bootstrap import run
except Exception as exc:  # pragma: no cover - corrupt install diagnostics
    sys.stderr.write("wob: failed to load the Wobble runtime: %s\\n" % (exc,))
    sys.stderr.write("wob: reinstall with: sh install.sh\\n")
    raise SystemExit(127)

if __name__ == "__main__":
    try:
        raise SystemExit(run())
    except KeyboardInterrupt:
        raise SystemExit(130)
'''


def _write_executable(path: Path, content: str) -> None:
    atomic_write_text(path, content)
    # 0755 explicitly: the temp file starts at 0600, and group/other need read
    # permission to execute a shell script.
    path.chmod(0o755)


def _read_manifest(install_root: Optional[Path] = None) -> Optional[Dict[str, Any]]:
    root = install_root or default_install_root()
    manifest = root / MANIFEST_NAME
    if not manifest.is_file():
        return None
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def _update_shell_path(bin_dir: Path) -> List[str]:
    """Add *bin_dir* to shell startup files idempotently. Returns touched files."""
    home = get_home()
    if bin_dir == home / ".local" / "bin":
        export_line = 'export PATH="$HOME/.local/bin:$PATH"'
    else:
        export_line = f'export PATH={shlex.quote(str(bin_dir))}:"$PATH"'

    block = f"# >>> wobble >>>\n{export_line}\n# <<< wobble <<<\n"
    candidates = [home / ".bashrc", home / ".zshrc", home / ".profile"]
    touched: List[str] = []

    existing = [c for c in candidates if c.exists()]
    if not existing:
        existing = [home / ".profile"]

    for conf in existing:
        try:
            text = conf.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if export_line in text or "# >>> wobble >>>" in text:
            continue
        try:
            with open(conf, "a", encoding="utf-8") as handle:
                if text and not text.endswith("\n"):
                    handle.write("\n")
                handle.write("\n" + block)
            touched.append(str(conf))
        except OSError:
            continue
    return touched


def _install_completions(install_root: Path) -> List[str]:
    home = get_home()
    targets = {
        "bash": home / ".local" / "share" / "bash-completion" / "completions" / "wob",
        "zsh": home / ".local" / "share" / "zsh" / "site-functions" / "_wob",
    }
    written: List[str] = []
    for shell, path in targets.items():
        script = COMPLETIONS.get(shell)
        if not script:
            continue
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(path, script)
            written.append(str(path))
        except OSError:
            continue
    return written


def _remove_completions(manifest: Optional[Dict[str, Any]]) -> List[str]:
    candidates: List[Path] = []
    if manifest and isinstance(manifest.get("completions"), list):
        candidates.extend(Path(p) for p in manifest["completions"])
    home = get_home()
    candidates.extend([
        home / ".local" / "share" / "bash-completion" / "completions" / "wob",
        home / ".local" / "share" / "zsh" / "site-functions" / "_wob",
    ])
    removed: List[str] = []
    for path in candidates:
        try:
            if path.is_file() and COMPLETION_MARKER in path.read_text(encoding="utf-8", errors="ignore"):
                path.unlink()
                removed.append(str(path))
        except OSError:
            continue
    return removed


def _candidate_launchers() -> List[Path]:
    paths = [default_bin_dir() / LAUNCHER_NAME]
    prefix = get_prefix()
    # Only touch $PREFIX/bin automatically inside Termux (user-owned prefix) or
    # when explicitly requested. A Linux system prefix is not ours to modify.
    if prefix and (is_termux() or os.environ.get("WOBBLE_PREFIX_LINK") == "1"):
        paths.append(prefix / "bin" / LAUNCHER_NAME)
    # de-duplicate while preserving order
    unique: List[Path] = []
    seen = set()
    for path in paths:
        key = str(path)
        if key not in seen:
            seen.add(key)
            unique.append(path)
    return unique


def _install_launcher_paths(bin_path: Path) -> List[Path]:
    """Launchers to create: the requested bin dir, plus $PREFIX/bin in Termux."""
    paths = [bin_path / LAUNCHER_NAME]
    prefix = get_prefix()
    if prefix and (is_termux() or os.environ.get("WOBBLE_PREFIX_LINK") == "1"):
        termux_launcher = prefix / "bin" / LAUNCHER_NAME
        if termux_launcher.parent != bin_path:
            paths.append(termux_launcher)
    return paths


def _copy_runtime(source_root: Path, destination: Path) -> None:
    source_pkg = source_root / "wobble"
    if not (source_pkg / "cli.py").is_file():
        raise InstallerError(
            f"'{source_root}' does not look like a Wobble source tree (wobble/cli.py missing)."
        )
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source_pkg, destination / "wobble", ignore=_IGNORED_COPY)
    for extra in ("LICENSE", "README.md", "AI_GUIDE.md"):
        candidate = source_root / extra
        if candidate.is_file():
            shutil.copy2(candidate, destination / extra)
    docs = source_root / "docs"
    if docs.is_dir():
        shutil.copytree(docs, destination / "docs", ignore=_IGNORED_COPY)
    _write_executable(destination / "wob.py", _BOOTSTRAP)
    atomic_write_text(destination / "VERSION", __version__ + "\n")


def _compile_runtime(app_dir: Path) -> None:
    """Precompile bytecode so first-run imports are as fast as possible."""
    try:
        import compileall
        compileall.compile_dir(
            str(app_dir / "wobble"), quiet=1, force=True, optimize=0,
            legacy=False, workers=0,
        )
        compileall.compile_file(str(app_dir / "wob.py"), quiet=1, force=True,
                                optimize=0, legacy=False)
    except Exception:
        # Bytecode is an optimisation only; never fail an install over it.
        pass


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------
def install(
    source_root: Optional[Path] = None,
    install_root: Optional[Path] = None,
    bin_dir: Optional[Path] = None,
    force: bool = False,
    completions: bool = True,
    update_path: bool = True,
) -> Dict[str, Any]:
    """Install Wobble as a standalone application and return a report."""
    started = time.monotonic()
    source = Path(source_root).expanduser().resolve() if source_root is not None else package_root()
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    if bin_dir:
        bin_path = Path(bin_dir).expanduser().resolve()
    else:
        existing = _read_manifest(root)
        recorded = Path(existing["launcher"]).parent if existing and existing.get("launcher") else None
        bin_path = recorded if recorded else default_bin_dir()

    _assert_safe_root(root)
    if not source.is_dir():
        raise InstallerError(f"Source directory not found: {source}")

    try:
        free = shutil.disk_usage(root.parent if root.parent.exists() else get_home()).free
    except OSError:
        free = 0
    if free and free < 5 * 1024 * 1024:
        raise InstallerError(
            "Not enough free disk space (need at least 5 MB) for the Wobble runtime."
        )

    root.mkdir(parents=True, exist_ok=True)
    bin_path.mkdir(parents=True, exist_ok=True)

    # Never clobber a foreign executable named `wob` without explicit consent.
    primary_launcher = bin_path / LAUNCHER_NAME
    if primary_launcher.exists() and not _is_our_launcher(primary_launcher) and not force:
        raise InstallerError(
            f"'{primary_launcher}' already exists and was not created by Wobble. "
            "Re-run with --force to replace it."
        )

    staging = root / f".app.tmp-{os.getpid()}"
    if staging.exists():
        shutil.rmtree(staging, ignore_errors=True)

    try:
        _copy_runtime(source, staging)
        _compile_runtime(staging)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise

    app_dir = root / APP_DIRNAME
    backup = root / ".app.old"
    if backup.exists():
        shutil.rmtree(backup, ignore_errors=True)
    swapped = False
    try:
        if app_dir.exists():
            os.replace(app_dir, backup)
        os.replace(staging, app_dir)
        swapped = True
    except Exception:
        if not app_dir.exists() and backup.exists():
            os.replace(backup, app_dir)
        shutil.rmtree(staging, ignore_errors=True)
        raise
    finally:
        if swapped:
            shutil.rmtree(backup, ignore_errors=True)

    python_fallback = sys.executable or "python3"
    launchers: List[str] = []
    launcher_script = _launcher_script(app_dir, python_fallback)
    for candidate in _install_launcher_paths(bin_path):
        try:
            if candidate.exists() and not _is_our_launcher(candidate) and candidate != primary_launcher and not force:
                continue
            if candidate.exists() or candidate.is_symlink():
                candidate.unlink()
            _write_executable(candidate, launcher_script)
            launchers.append(str(candidate))
        except OSError:
            continue

    completion_files = _install_completions(root) if completions else []
    touched_shells = _update_shell_path(bin_path) if update_path else []

    files: Dict[str, Dict[str, Any]] = {}
    total_bytes = 0
    for path in _iter_files(app_dir):
        rel = path.relative_to(app_dir).as_posix()
        try:
            size = path.stat().st_size
            digest = _sha256_file(path)
        except OSError:
            continue
        files[rel] = {"sha256": digest, "size": size}
        total_bytes += size

    manifest = {
        "schema": INSTALL_SCHEMA,
        "name": "wobble",
        "version": __version__,
        "installed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "install_root": str(root),
        "app_dir": str(app_dir),
        "launcher": str(primary_launcher),
        "launchers": launchers,
        "completions": completion_files,
        "shell_configs": touched_shells,
        "python": python_fallback,
        "source": str(source),
        "standalone": True,
        "files": files,
        "file_count": len(files),
        "total_bytes": total_bytes,
    }
    atomic_write_json(root / MANIFEST_NAME, manifest)

    result = dict(manifest)
    result["elapsed_seconds"] = round(time.monotonic() - started, 3)
    result["source_is_installed_app"] = source == app_dir
    return result


def uninstall(
    install_root: Optional[Path] = None,
    purge: bool = False,
) -> Dict[str, Any]:
    """Remove the installed runtime and launchers. Projects are never touched."""
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    _assert_safe_root(root)
    manifest = _read_manifest(root)

    removed: List[str] = []
    kept: List[str] = []

    launchers: List[Path] = []
    if manifest and isinstance(manifest.get("launchers"), list):
        launchers.extend(Path(p) for p in manifest["launchers"])
    if manifest and manifest.get("launcher"):
        launchers.append(Path(manifest["launcher"]))
    launchers.extend(_candidate_launchers())

    seen = set()
    for launcher in launchers:
        key = str(launcher)
        if key in seen:
            continue
        seen.add(key)
        try:
            if launcher.is_symlink() and _is_our_launcher(launcher):
                launcher.unlink()
                removed.append(key)
            elif launcher.is_file() and _is_our_launcher(launcher):
                launcher.unlink()
                removed.append(key)
        except OSError:
            kept.append(key)

    for path in _remove_completions(manifest):
        removed.append(path)

    # Remove staging leftovers, old backups, app directory, and manifest.
    for name in (APP_DIRNAME, ".app.old"):
        target = root / name
        if target.exists():
            shutil.rmtree(target, ignore_errors=True)
            if not target.exists():
                removed.append(str(target))
    for leftover in root.glob(".app.tmp-*"):
        shutil.rmtree(leftover, ignore_errors=True)
    manifest_path = root / MANIFEST_NAME
    if manifest_path.exists():
        try:
            manifest_path.unlink()
            removed.append(str(manifest_path))
        except OSError:
            pass
    try:
        root.rmdir()  # only if empty; never force-delete unknown user data
        removed.append(str(root))
    except OSError:
        if root.exists():
            kept.append(str(root))

    purged: List[str] = []
    if purge:
        for data_dir in (get_home() / ".wobble", get_home() / ".config" / "wobble"):
            if data_dir.is_dir():
                shutil.rmtree(data_dir, ignore_errors=True)
                if not data_dir.exists():
                    purged.append(str(data_dir))

    return {
        "success": True,
        "install_root": str(root),
        "removed": removed,
        "kept": kept,
        "purged": purged,
        "projects_preserved": True,
    }


def status(install_root: Optional[Path] = None) -> Dict[str, Any]:
    """Report whether Wobble is installed standalone, or via a legacy symlink."""
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    manifest = _read_manifest(root)
    launcher = default_bin_dir() / LAUNCHER_NAME

    if not manifest:
        legacy = None
        try:
            if launcher.is_symlink():
                legacy = os.readlink(str(launcher))
        except OSError:
            legacy = None
        return {
            "installed": False,
            "mode": "legacy-symlink" if legacy else "source-checkout",
            "install_root": str(root),
            "launcher": str(launcher) if (launcher.exists() or launcher.is_symlink()) else None,
            "legacy_target": legacy,
            "standalone": False,
            "version": __version__,
            "message": (
                "Legacy symlink install detected: deleting the source checkout breaks 'wob'."
                if legacy else
                "Wobble is running from a source checkout (not installed as software)."
            ),
        }

    app_dir = Path(manifest.get("app_dir", root / APP_DIRNAME))
    launcher_path = Path(manifest.get("launcher", launcher))
    source = manifest.get("source")
    data = {
        "installed": True,
        "mode": "standalone",
        "standalone": True,
        "version": manifest.get("version"),
        "installed_at": manifest.get("installed_at"),
        "install_root": str(root),
        "app_dir": str(app_dir),
        "launcher": str(launcher_path) if launcher_path.exists() else None,
        "launchers": manifest.get("launchers", []),
        "completions": manifest.get("completions", []),
        "python": manifest.get("python"),
        "file_count": manifest.get("file_count", 0),
        "total_bytes": manifest.get("total_bytes", 0),
        "source": source,
        "source_exists": bool(source and Path(source).exists()),
        "healthy": app_dir.is_dir() and (app_dir / "wob.py").is_file(),
    }
    if not data["source_exists"]:
        data["message"] = "Source checkout is gone, but the installed runtime is independent of it."
    return data


def verify(install_root: Optional[Path] = None) -> Dict[str, Any]:
    """Check installed files against the manifest hashes."""
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    manifest = _read_manifest(root)
    if not manifest:
        return {"ok": False, "error": "No install manifest found", "install_root": str(root)}

    app_dir = Path(manifest.get("app_dir", root / APP_DIRNAME))
    files = manifest.get("files", {})
    missing: List[str] = []
    modified: List[str] = []
    checked = 0

    for rel, meta in files.items():
        target = app_dir / rel
        if not target.is_file():
            missing.append(rel)
            continue
        checked += 1
        try:
            if target.stat().st_size != meta.get("size", -1) or _sha256_file(target) != meta.get("sha256"):
                modified.append(rel)
        except OSError:
            missing.append(rel)

    launcher = Path(manifest.get("launcher", default_bin_dir() / LAUNCHER_NAME))
    launcher_ok = _is_our_launcher(launcher)
    ok = not missing and not modified and launcher_ok
    return {
        "ok": ok,
        "version": manifest.get("version"),
        "checked": checked,
        "file_count": len(files),
        "missing": missing,
        "modified": modified,
        "launcher_ok": launcher_ok,
        "install_root": str(root),
        "source_exists": bool(manifest.get("source") and Path(manifest["source"]).exists()),
    }


def uninstall_legacy_symlink() -> Optional[str]:
    """Remove a pre-1.2 symlink launcher that points into a source checkout."""
    launcher = default_bin_dir() / LAUNCHER_NAME
    try:
        if launcher.is_symlink():
            target = os.readlink(str(launcher))
            if "wobble" in target:
                launcher.unlink()
                return target
    except OSError:
        return None
    return None
