"""
Wobble Standalone Installer
Turns Wobble into a real, self-contained piece of software.

The classic ``git clone`` + symlink setup breaks the moment the checkout is
deleted. This installer instead copies the runtime into a private application
directory, precompiles bytecode, and writes a launcher that never references the
source checkout again.

Layout (defaults, override with ``WOBBLE_INSTALL_DIR``)::

    ~/.local/share/wobble/
        app/                 <- the installed runtime (self-contained)
            wob.py           <- bootstrap
            wobble/          <- Python package (+ __pycache__)
            LICENSE
        install.json         <- manifest: version, files, hashes, launchers
    ~/.local/bin/wob         <- generated POSIX-sh launcher
"""

from __future__ import annotations

import os
import re
import shlex
import shutil
import sys
import time
from pathlib import Path

from wobble import __version__
from wobble.core.context import get_home, get_prefix, is_termux
from wobble.core.fsutil import atomic_write_json, atomic_write_text

# NOTE: hashlib, concurrent.futures, and the (large) completion scripts are
# imported lazily. `wob self status` must not pay for the hashing or shell
# completion machinery just to inspect a manifest and a launcher.

INSTALL_SCHEMA = 1
APP_DIRNAME = "app"
MANIFEST_NAME = "install.json"
LAUNCHER_NAME = "wob"
LAUNCHER_MARKER = "Wobble launcher (auto-generated by `wob self install`)"
RESCUE_LAUNCHER_NAME = "wob-rescue"
RESCUE_LAUNCHER_MARKER = "Wobble rescue launcher (auto-generated by `wob self install`)"
COMPLETION_MARKER = "Wobble (wob)"
# Prevent installing onto top-level system folders or deleting them on uninstall.
_UNSAFE_ROOTS = {
    Path("/"), Path("/system"), Path("/data"), Path("/storage"), Path("/sdcard"),
}
_IGNORED_COPY = shutil.ignore_patterns(
    "__pycache__", "*.pyc", "*.pyo", "*.apk", ".git", ".github", ".wobble",
)


class InstallerError(RuntimeError):
    """Raised when an install/uninstall operation cannot be performed safely."""


# ---------------------------------------------------------------------------
# Paths & helpers
# ---------------------------------------------------------------------------
def running_install_root() -> Optional[Path]:
    """
    If this module is executing from an installed app directory
    (``<root>/app/wobble/core/installer.py``), return ``<root>``.

    This makes custom install locations work without exporting environment
    variables in every shell.
    """
    try:
        app_dir = Path(__file__).resolve().parents[2]
    except IndexError:
        return None
    if app_dir.name == APP_DIRNAME and (app_dir / "wob.py").is_file():
        return app_dir.parent
    return None


def default_install_root() -> Path:
    override = os.environ.get("WOBBLE_INSTALL_DIR")
    if override:
        return Path(override).expanduser()
    discovered = running_install_root()
    if discovered is not None:
        return discovered
    return get_home() / ".local" / "share" / "wobble"


def default_bin_dir() -> Path:
    override = os.environ.get("WOBBLE_BIN_DIR")
    if override:
        return Path(override).expanduser()
    return get_home() / ".local" / "bin"


def package_root() -> Path:
    """Return the repository root, or the installed app directory."""
    # wobble/core/installer.py -> repository (or installed app) root
    return Path(__file__).resolve().parents[2]


def _sha256_file(path: Path) -> str:
    import hashlib

    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(256 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _iter_files(root: Path) -> Iterable[Path]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d != "__pycache__")
        for name in sorted(filenames):
            if name.endswith((".pyc", ".pyo")):
                continue
            yield Path(dirpath) / name


def _assert_safe_root(path: Path) -> None:
    if not path.is_absolute():
        raise InstallerError(f"Install location must be an absolute path: {path}")
    if path in _UNSAFE_ROOTS or path == get_home().resolve():
        raise InstallerError(f"Refusing to use unsafe install location: {path}")
    if len(path.parts) < 3:
        raise InstallerError(f"Refusing to use overly broad install location: {path}")


def _is_our_launcher(path: Path) -> bool:
    """Return True when *path* is a launcher this installer wrote."""
    try:
        if path.is_symlink():
            target = os.readlink(str(path))
            return "wobble" in target and target.rstrip("/").endswith("bin/wob")
        if path.is_file():
            text = path.read_text(encoding="utf-8", errors="ignore")[:4096]
            return LAUNCHER_MARKER in text or RESCUE_LAUNCHER_MARKER in text
    except OSError:
        return False
    return False


def _source_version(source_root: Path) -> Optional[str]:
    """Read ``__version__`` from a source tree without importing it."""
    try:
        text = (Path(source_root) / "wobble" / "__init__.py").read_text(
            encoding="utf-8", errors="ignore")
    except OSError:
        return None
    match = re.search(r"__version__\s*=\s*[\"']([^\"']+)", text)
    return match.group(1) if match else None


def _launcher_script(app_dir: Path, python_fallback: str) -> str:
    app = shlex.quote(str(app_dir))
    root = shlex.quote(str(Path(app_dir).parent))
    fallback = shlex.quote(python_fallback)
    return f"""#!/usr/bin/env sh
# {LAUNCHER_MARKER}.
# This file is standalone: it only needs the installed app below and does not
# reference (or depend on) the source checkout Wobble was installed from.
APP={app}
ROOT={root}
RESCUE="$ROOT/rescue.sh"
# Self-healing: if the runtime is gone, restore it from the offline snapshot
# before giving up. Set WOBBLE_AUTO_RESCUE=0 to disable.
auto_rescue() {{
    [ "${{WOBBLE_AUTO_RESCUE:-1}}" = "0" ] && return 1
    [ -f "$RESCUE" ] || return 1
    echo "wob: $1; restoring the runtime from the offline snapshot..." >&2
    sh "$RESCUE" --quiet >&2 || return 1
    [ -f "$APP/wob.py" ]
}}
if [ ! -f "$APP/wob.py" ]; then
    auto_rescue "installation is damaged ($APP/wob.py is missing)" || {{
        echo "wob: could not restore the installation automatically." >&2
        echo "wob: run: sh $RESCUE   (or reinstall: sh install.sh)" >&2
        exit 127
    }}
fi
if [ -n "${{WOBBLE_PYTHON:-}}" ] && [ -x "${{WOBBLE_PYTHON}}" ]; then
    PY="$WOBBLE_PYTHON"
elif command -v python3 >/dev/null 2>&1; then
    PY=python3
elif command -v python >/dev/null 2>&1; then
    PY=python
elif [ -x {fallback} ]; then
    PY={fallback}
else
    echo "wob: Python 3 is required but was not found in PATH." >&2
    echo "wob: install Python 3.8+ first (Termux: pkg install -y python)" >&2
    exit 127
fi
"$PY" "$APP/wob.py" "$@"
status=$?
# Exit code 121 is reserved for "the runtime could not be loaded" (everything
# else, including 127 from a missing external tool, is the command's own code).
# Repair once and retry a single time, then report honestly.
if [ "$status" -eq 121 ] && [ -f "$APP/wob.py" ]; then
    if auto_rescue "the runtime failed to load"; then
        "$PY" "$APP/wob.py" "$@"
        status=$?
    else
        echo "wob: could not restore the installation automatically." >&2
        echo "wob: run: sh $RESCUE   (or reinstall: sh install.sh)" >&2
    fi
fi
exit $status
"""


_BOOTSTRAP = '''#!/usr/bin/env python3
"""Wobble installed bootstrap (generated by the installer)."""

import os
import sys

APP_DIR = os.path.dirname(os.path.abspath(__file__))
if APP_DIR in sys.path:
    sys.path.remove(APP_DIR)
sys.path.insert(0, APP_DIR)

try:
    from wobble.bootstrap import run
except Exception as exc:  # pragma: no cover - corrupt install diagnostics
    sys.stderr.write("wob: failed to load the Wobble runtime: %s\\n" % (exc,))
    sys.stderr.write("wob: attempting recovery is handled by the launcher; "
                     "if it fails: sh install.sh\\n")
    raise SystemExit(121)

if __name__ == "__main__":
    try:
        raise SystemExit(run())
    except KeyboardInterrupt:
        raise SystemExit(130)
'''


def _write_executable(path: Path, content: str) -> None:
    atomic_write_text(path, content)
    # 0755 explicitly: the temp file starts at 0600, and group/other need read
    # permission to execute a shell script.
    path.chmod(0o755)


def _read_manifest(install_root: Optional[Path] = None) -> Optional[Dict[str, Any]]:
    import json

    root = install_root or default_install_root()
    manifest = root / MANIFEST_NAME
    if not manifest.is_file():
        return None
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def read_manifest(install_root: Optional[Path] = None) -> Optional[Dict[str, Any]]:
    """Public, never-raising manifest reader used by the self-check engine."""
    return _read_manifest(install_root)


def manifest_path(install_root: Optional[Path] = None) -> Path:
    """Path of the install manifest for *install_root*."""
    return (install_root or default_install_root()) / MANIFEST_NAME


def _update_shell_path(bin_dir: Path) -> List[str]:
    """Add *bin_dir* to shell startup files idempotently. Returns touched files."""
    home = get_home()
    if bin_dir == home / ".local" / "bin":
        export_line = 'export PATH="$HOME/.local/bin:$PATH"'
    else:
        export_line = f'export PATH={shlex.quote(str(bin_dir))}:"$PATH"'

    block = f"# >>> wobble >>>\n{export_line}\n# <<< wobble <<<\n"
    candidates = [home / ".bashrc", home / ".zshrc", home / ".profile"]
    touched: List[str] = []

    existing = [c for c in candidates if c.exists()]
    if not existing:
        existing = [home / ".profile"]

    for conf in existing:
        try:
            text = conf.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if export_line in text or "# >>> wobble >>>" in text:
            continue
        try:
            with open(conf, "a", encoding="utf-8") as handle:
                if text and not text.endswith("\n"):
                    handle.write("\n")
                handle.write("\n" + block)
            touched.append(str(conf))
        except OSError:
            continue
    return touched


def _install_completions(install_root: Path) -> List[str]:
    from wobble.core.completions import COMPLETIONS

    home = get_home()
    targets = {
        "bash": home / ".local" / "share" / "bash-completion" / "completions" / "wob",
        "zsh": home / ".local" / "share" / "zsh" / "site-functions" / "_wob",
    }
    written: List[str] = []
    for shell, path in targets.items():
        script = COMPLETIONS.get(shell)
        if not script:
            continue
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            atomic_write_text(path, script)
            written.append(str(path))
        except OSError:
            continue
    return written


def _remove_completions(manifest: Optional[Dict[str, Any]]) -> List[str]:
    candidates: List[Path] = []
    if manifest and isinstance(manifest.get("completions"), list):
        candidates.extend(Path(p) for p in manifest["completions"])
    home = get_home()
    candidates.extend([
        home / ".local" / "share" / "bash-completion" / "completions" / "wob",
        home / ".local" / "share" / "zsh" / "site-functions" / "_wob",
    ])
    removed: List[str] = []
    for path in candidates:
        try:
            if path.is_file() and COMPLETION_MARKER in path.read_text(encoding="utf-8", errors="ignore"):
                path.unlink()
                removed.append(str(path))
        except OSError:
            continue
    return removed


def _candidate_launchers() -> List[Path]:
    paths = [default_bin_dir() / LAUNCHER_NAME]
    prefix = get_prefix()
    # Only touch $PREFIX/bin automatically inside Termux (user-owned prefix) or
    # when explicitly requested. A Linux system prefix is not ours to modify.
    if prefix and (is_termux() or os.environ.get("WOBBLE_PREFIX_LINK") == "1"):
        paths.append(prefix / "bin" / LAUNCHER_NAME)
    # de-duplicate while preserving order
    unique: List[Path] = []
    seen = set()
    for path in paths:
        key = str(path)
        if key not in seen:
            seen.add(key)
            unique.append(path)
    return unique


def _install_launcher_paths(bin_path: Path) -> List[Path]:
    """Launchers to create: the requested bin dir, plus $PREFIX/bin in Termux."""
    paths = [bin_path / LAUNCHER_NAME]
    prefix = get_prefix()
    if prefix and (is_termux() or os.environ.get("WOBBLE_PREFIX_LINK") == "1"):
        termux_launcher = prefix / "bin" / LAUNCHER_NAME
        if termux_launcher.parent != bin_path:
            paths.append(termux_launcher)
    return paths


def _copy_runtime(source_root: Path, destination: Path) -> None:
    source_pkg = source_root / "wobble"
    if not (source_pkg / "cli.py").is_file():
        raise InstallerError(
            f"'{source_root}' does not look like a Wobble source tree (wobble/cli.py missing)."
        )
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source_pkg, destination / "wobble", ignore=_IGNORED_COPY)
    for extra in ("LICENSE", "README.md", "AI_GUIDE.md"):
        candidate = source_root / extra
        if candidate.is_file():
            shutil.copy2(candidate, destination / extra)
    docs = source_root / "docs"
    if docs.is_dir():
        shutil.copytree(docs, destination / "docs", ignore=_IGNORED_COPY)
    _write_executable(destination / "wob.py", _BOOTSTRAP)
    atomic_write_text(destination / "VERSION", __version__ + "\n")


def _compile_runtime(app_dir: Path) -> None:
    """Precompile bytecode so first-run imports are as fast as possible."""
    try:
        import compileall
        compileall.compile_dir(
            str(app_dir / "wobble"), quiet=1, force=True, optimize=0,
            legacy=False, workers=0,
        )
        compileall.compile_file(str(app_dir / "wob.py"), quiet=1, force=True,
                                optimize=0, legacy=False)
    except Exception:
        # Bytecode is an optimisation only; never fail an install over it.
        pass


def compile_runtime(app_dir: Path) -> Dict[str, Any]:
    """Precompile *app_dir* bytecode. Returns ``{"ok", "pyc_files", "elapsed_ms"}``.

    Bytecode is purely an optimisation: a failure is reported, never raised.
    """
    started = time.monotonic()
    _compile_runtime(app_dir)
    pyc = 0
    try:
        for dirpath, dirnames, filenames in os.walk(app_dir / "wobble"):
            if "__pycache__" in dirnames:
                pyc += sum(1 for name in os.listdir(os.path.join(dirpath, "__pycache__"))
                           if name.endswith(".pyc"))
    except OSError:
        pyc = 0
    return {
        "ok": pyc > 0,
        "pyc_files": pyc,
        "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
    }


def install_completions(install_root: Path) -> List[str]:
    """Public wrapper that regenerates shell completion files."""
    return _install_completions(install_root)


def update_shell_path(bin_dir: Path) -> List[str]:
    """Public wrapper that adds *bin_dir* to shell startup files."""
    return _update_shell_path(bin_dir)


def cleanup_leftovers(install_root: Path) -> List[str]:
    """Remove staging directories and backups left by an interrupted install."""
    removed: List[str] = []
    root = Path(install_root)
    for pattern in (".app.tmp-*", ".app.old", ".snapshot.tmp-*", ".snapshot.old"):
        for leftover in root.glob(pattern):
            shutil.rmtree(leftover, ignore_errors=True)
            if not leftover.exists():
                removed.append(str(leftover))
    return removed


def rewrite_launchers(
    app_dir: Path,
    bin_dir: Optional[Path] = None,
    launchers: Optional[Iterable[str]] = None,
) -> Dict[str, Any]:
    """(Re)write the generated launcher scripts so they point at *app_dir*.

    Used by ``wob self repair``. Existing foreign executables named ``wob`` are
    never replaced: only launchers carrying Wobble's marker are overwritten.
    """
    candidates: List[Path] = []
    if launchers:
        candidates.extend(Path(p) for p in launchers)
    if bin_dir:
        candidates.append(Path(bin_dir) / LAUNCHER_NAME)
    candidates.extend(_candidate_launchers())

    seen = set()
    written: List[str] = []
    failed: List[str] = []
    skipped: List[str] = []
    script = _launcher_script(app_dir, sys.executable or "python3")
    for candidate in candidates:
        key = str(candidate)
        if key in seen:
            continue
        seen.add(key)
        try:
            if candidate.exists() and not candidate.is_symlink() and not _is_our_launcher(candidate):
                skipped.append(key)
                continue
            candidate.parent.mkdir(parents=True, exist_ok=True)
            if candidate.is_symlink() or candidate.exists():
                candidate.unlink()
            _write_executable(candidate, script)
            written.append(key)
        except OSError:
            failed.append(key)
    return {"written": written, "failed": failed, "skipped": skipped}


def refresh_manifest(install_root: Optional[Path] = None) -> Dict[str, Any]:
    """Recompute the manifest file hashes from the installed runtime.

    ``wob self repair --accept-current`` uses this after a deliberate local
    patch. It never touches project files.
    """
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    manifest = _read_manifest(root)
    if not manifest:
        raise InstallerError("No install manifest found; run 'wob self install' first.")
    app_dir = Path(manifest.get("app_dir", root / APP_DIRNAME))
    if not app_dir.is_dir():
        raise InstallerError(f"Installed runtime is missing: {app_dir}")

    files: Dict[str, Dict[str, Any]] = {}
    total_bytes = 0
    for path in _iter_files(app_dir):
        rel = path.relative_to(app_dir).as_posix()
        try:
            size = path.stat().st_size
            digest = _sha256_file(path)
        except OSError:
            continue
        files[rel] = {"sha256": digest, "size": size}
        total_bytes += size

    manifest["files"] = files
    manifest["file_count"] = len(files)
    manifest["total_bytes"] = total_bytes
    manifest["verified_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    atomic_write_json(manifest_path(root), manifest)
    return {"ok": True, "file_count": len(files), "total_bytes": total_bytes,
            "install_root": str(root)}


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------
def _hash_tree(root: Path, workers=None):
    """Hash every file under *root* in parallel.

    SHA-256 of a few hundred small files is I/O bound; on a phone the thread
    pool still helps because each read releases the GIL. Ordering stays stable
    so manifests are diffable across installs.
    """
    from concurrent.futures import ThreadPoolExecutor

    paths = list(_iter_files(root))
    if not paths:
        return {}, 0
    workers = workers or min(8, max(2, (os.cpu_count() or 2) * 2), len(paths))

    def one(path: Path):
        rel = path.relative_to(root).as_posix()
        try:
            return rel, path.stat().st_size, _sha256_file(path)
        except OSError:
            return rel, None, None

    results = []
    if len(paths) < 4:
        results = [one(path) for path in paths]
    else:
        with ThreadPoolExecutor(max_workers=workers) as pool:
            results = list(pool.map(one, paths))

    files: Dict[str, Dict[str, Any]] = {}
    total = 0
    for rel, size, digest in results:
        if size is None or digest is None:
            continue
        files[rel] = {"sha256": digest, "size": size}
        total += size
    return files, total


def install(
    source_root: Optional[Path] = None,
    install_root: Optional[Path] = None,
    bin_dir: Optional[Path] = None,
    force: bool = False,
    completions: bool = True,
    update_path: bool = True,
    snapshot: bool = True,
) -> Dict[str, Any]:
    """Install Wobble as a standalone application and return a report."""
    started = time.monotonic()
    source = Path(source_root).expanduser().resolve() if source_root is not None else package_root()
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    if bin_dir:
        bin_path = Path(bin_dir).expanduser().resolve()
    else:
        existing = _read_manifest(root)
        recorded = Path(existing["launcher"]).parent if existing and existing.get("launcher") else None
        bin_path = recorded if recorded else default_bin_dir()

    _assert_safe_root(root)
    if not source.is_dir():
        raise InstallerError(f"Source directory not found: {source}")

    try:
        free = shutil.disk_usage(root.parent if root.parent.exists() else get_home()).free
    except OSError:
        free = 0
    if free and free < 5 * 1024 * 1024:
        raise InstallerError(
            "Not enough free disk space (need at least 5 MB) for the Wobble runtime."
        )

    root.mkdir(parents=True, exist_ok=True)
    bin_path.mkdir(parents=True, exist_ok=True)

    # Never clobber a foreign executable named `wob` without explicit consent.
    primary_launcher = bin_path / LAUNCHER_NAME
    if primary_launcher.exists() and not _is_our_launcher(primary_launcher) and not force:
        raise InstallerError(
            f"'{primary_launcher}' already exists and was not created by Wobble. "
            "Re-run with --force to replace it."
        )

    staging = root / f".app.tmp-{os.getpid()}"
    if staging.exists():
        shutil.rmtree(staging, ignore_errors=True)

    try:
        _copy_runtime(source, staging)
        _compile_runtime(staging)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise

    app_dir = root / APP_DIRNAME
    backup = root / ".app.old"
    if backup.exists():
        shutil.rmtree(backup, ignore_errors=True)
    swapped = False
    try:
        if app_dir.exists():
            os.replace(app_dir, backup)
        os.replace(staging, app_dir)
        swapped = True
    except Exception:
        if not app_dir.exists() and backup.exists():
            os.replace(backup, app_dir)
        shutil.rmtree(staging, ignore_errors=True)
        raise
    finally:
        if swapped:
            shutil.rmtree(backup, ignore_errors=True)

    python_fallback = sys.executable or "python3"
    launchers: List[str] = []
    launcher_script = _launcher_script(app_dir, python_fallback)
    for candidate in _install_launcher_paths(bin_path):
        try:
            if candidate.exists() and not _is_our_launcher(candidate) and candidate != primary_launcher and not force:
                continue
            if candidate.exists() or candidate.is_symlink():
                candidate.unlink()
            _write_executable(candidate, launcher_script)
            launchers.append(str(candidate))
        except OSError:
            continue

    completion_files = _install_completions(root) if completions else []
    touched_shells = _update_shell_path(bin_path) if update_path else []

    files, total_bytes = _hash_tree(app_dir)

    source_version = _source_version(source)
    manifest = {
        "schema": INSTALL_SCHEMA,
        "name": "wobble",
        "version": source_version or __version__,
        "running_version": __version__,
        "installed_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "install_root": str(root),
        "app_dir": str(app_dir),
        "launcher": str(primary_launcher),
        "launchers": launchers,
        "completions": completion_files,
        "shell_configs": touched_shells,
        "python": python_fallback,
        "source": str(source),
        "standalone": True,
        "files": files,
        "file_count": len(files),
        "total_bytes": total_bytes,
    }
    atomic_write_json(root / MANIFEST_NAME, manifest)

    # Recovery assets are part of every install: an offline snapshot plus
    # out-of-band rescue scripts that live *outside* the runtime, because the
    # runtime is exactly what will be broken when they are needed.
    from wobble.core import recovery

    recovery_info = {}
    if snapshot:
        try:
            recovery_info["snapshot"] = recovery.create_snapshot(
                root, app_dir=app_dir, version=manifest["version"],
                trusted_files=files, source=str(source),
            )
        except (recovery.RecoveryError, OSError) as exc:
            recovery_info["snapshot"] = {"ok": False, "error": str(exc)}
    else:
        recovery_info["snapshot"] = {"ok": False, "skipped": True,
                                     "error": "disabled with --no-snapshot"}
    try:
        recovery_info["rescue"] = recovery.write_rescue_assets(
            root, bin_dir=bin_path, python=python_fallback)
        recovery_info["rescue_launchers"] = recovery_info["rescue"].get("launchers", [])
    except OSError as exc:
        recovery_info["rescue"] = {"ok": False, "error": str(exc)}
        recovery_info["rescue_launchers"] = []
    manifest.update(recovery_info)
    try:
        atomic_write_json(root / MANIFEST_NAME, manifest)
    except OSError:
        pass

    result = dict(manifest)
    result["elapsed_seconds"] = round(time.monotonic() - started, 3)
    result["source_is_installed_app"] = source == app_dir
    return result


def uninstall(
    install_root: Optional[Path] = None,
    purge: bool = False,
) -> Dict[str, Any]:
    """Remove the installed runtime and launchers. Projects are never touched."""
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    _assert_safe_root(root)
    manifest = _read_manifest(root)

    removed: List[str] = []
    kept: List[str] = []

    launchers: List[Path] = []
    if manifest and isinstance(manifest.get("launchers"), list):
        launchers.extend(Path(p) for p in manifest["launchers"])
    if manifest and manifest.get("launcher"):
        launchers.append(Path(manifest["launcher"]))
    launchers.extend(_candidate_launchers())

    rescue_launchers: List[Path] = []
    if manifest and isinstance(manifest.get("rescue_launchers"), list):
        rescue_launchers.extend(Path(p) for p in manifest["rescue_launchers"])
    for launcher in launchers:
        if launcher.name == LAUNCHER_NAME:
            rescue_launchers.append(launcher.parent / RESCUE_LAUNCHER_NAME)
    rescue_launchers.extend(p.parent / RESCUE_LAUNCHER_NAME
                            for p in _candidate_launchers())
    launchers.extend(rescue_launchers)

    seen = set()
    for launcher in launchers:
        key = str(launcher)
        if key in seen:
            continue
        seen.add(key)
        try:
            if launcher.is_symlink() and _is_our_launcher(launcher):
                launcher.unlink()
                removed.append(key)
            elif launcher.is_file() and _is_our_launcher(launcher):
                launcher.unlink()
                removed.append(key)
        except OSError:
            kept.append(key)

    for path in _remove_completions(manifest):
        removed.append(path)

    # Remove staging leftovers, old backups, the recovery snapshot, repair
    # backups, rescue scripts, the app directory, and the manifest.
    for name in (APP_DIRNAME, ".app.old", "snapshot", ".snapshot.old",
                 "repair-backups"):
        target = root / name
        if target.exists():
            shutil.rmtree(target, ignore_errors=True)
            if not target.exists():
                removed.append(str(target))
    for name in ("rescue.py", "rescue.sh"):
        target = root / name
        if target.is_file():
            try:
                target.unlink()
                removed.append(str(target))
            except OSError:
                kept.append(str(target))
    for leftover in root.glob(".app.tmp-*"):
        shutil.rmtree(leftover, ignore_errors=True)
    manifest_path = root / MANIFEST_NAME
    if manifest_path.exists():
        try:
            manifest_path.unlink()
            removed.append(str(manifest_path))
        except OSError:
            pass
    try:
        root.rmdir()  # only if empty; never force-delete unknown user data
        removed.append(str(root))
    except OSError:
        if root.exists():
            kept.append(str(root))

    purged: List[str] = []
    if purge:
        for data_dir in (get_home() / ".wobble", get_home() / ".config" / "wobble"):
            if data_dir.is_dir():
                shutil.rmtree(data_dir, ignore_errors=True)
                if not data_dir.exists():
                    purged.append(str(data_dir))

    return {
        "success": True,
        "install_root": str(root),
        "removed": removed,
        "kept": kept,
        "purged": purged,
        "projects_preserved": True,
    }


def _launcher_state(path: Path) -> Dict[str, Any]:
    """Describe a launcher path without executing anything."""
    state = {
        "path": str(path),
        "exists": False,
        "is_ours": False,
        "executable": False,
        "app_dir": None,
    }
    try:
        state["exists"] = path.exists() or path.is_symlink()
        if not state["exists"]:
            return state
        state["is_ours"] = _is_our_launcher(path)
        state["executable"] = os.access(str(path), os.X_OK)
        if path.is_file() and not path.is_symlink():
            text = path.read_text(encoding="utf-8", errors="ignore")[:4096]
            for line in text.splitlines():
                if line.startswith("APP="):
                    state["app_dir"] = line.split("=", 1)[1].strip().strip("'\"")
                    break
    except OSError:
        pass
    return state


def status(install_root: Optional[Path] = None) -> Dict[str, Any]:
    """Report the installation mode, layout, and quick health signals.

    This is intentionally cheap: no file hashing and no subprocesses. It answers
    "is this a standalone install, and do the pieces still line up?" in a few
    milliseconds so ``wob self status`` can run on every shell prompt.
    """
    started = time.monotonic()
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    manifest = _read_manifest(root)
    default_launcher = default_bin_dir() / LAUNCHER_NAME

    if not manifest:
        legacy = None
        try:
            if default_launcher.is_symlink():
                legacy = os.readlink(str(default_launcher))
        except OSError:
            legacy = None
        launcher_exists = default_launcher.exists() or default_launcher.is_symlink()
        return {
            "installed": False,
            "mode": "legacy-symlink" if legacy else "source-checkout",
            "standalone": False,
            "install_root": str(root),
            "manifest": str(manifest_path(root)),
            "launcher": str(default_launcher) if launcher_exists else None,
            "launchers": [],
            "legacy_target": legacy,
            "version": __version__,
            "manifest_version": None,
            "python": sys.executable or "python3",
            "healthy": False,
            "launcher_ok": False,
            "runtime_ok": False,
            "file_count": 0,
            "total_bytes": 0,
            "installed_at": None,
            "in_path": str(default_launcher.parent) in os.environ.get("PATH", "").split(os.pathsep),
            "elapsed_ms": round((time.monotonic() - started) * 1000, 2),
            "message": (
                "Legacy symlink install detected: deleting the source checkout breaks 'wob'."
                if legacy else
                "Wobble is running from a source checkout (not installed as software)."
            ),
        }

    app_dir = Path(manifest.get("app_dir", root / APP_DIRNAME))
    launcher_path = Path(manifest.get("launcher", default_launcher))
    source = manifest.get("source")

    runtime_ok = bool(
        app_dir.is_dir()
        and (app_dir / "wob.py").is_file()
        and (app_dir / "wobble" / "cli.py").is_file()
    )
    launcher_state = _launcher_state(launcher_path)
    launcher_ok = bool(
        launcher_state["exists"]
        and launcher_state["is_ours"]
        and launcher_state["executable"]
        and launcher_state["app_dir"] in (None, str(app_dir))
    )
    bin_dir = launcher_path.parent
    in_path = str(bin_dir) in os.environ.get("PATH", "").split(os.pathsep)

    data = {
        "installed": True,
        "mode": "standalone",
        "standalone": True,
        "version": __version__,
        "manifest_version": manifest.get("version"),
        "manifest_schema": manifest.get("schema"),
        "installed_at": manifest.get("installed_at"),
        "install_root": str(root),
        "manifest": str(manifest_path(root)),
        "app_dir": str(app_dir),
        "launcher": str(launcher_path) if launcher_state["exists"] else None,
        "launcher_expected": str(launcher_path),
        "launcher_ok": launcher_ok,
        "launcher_state": launcher_state,
        "launchers": manifest.get("launchers", []),
        "bin_dir": str(bin_dir),
        "in_path": in_path,
        "completions": manifest.get("completions", []),
        "python": manifest.get("python"),
        "python_running": sys.executable or "python3",
        "file_count": manifest.get("file_count", 0),
        "total_bytes": manifest.get("total_bytes", 0),
        "runtime_ok": runtime_ok,
        "healthy": runtime_ok and launcher_ok,
        "source": source,
        "source_exists": bool(source and Path(source).exists()),
        "version_matches": manifest.get("version") == __version__,
        "elapsed_ms": round((time.monotonic() - started) * 1000, 2),
    }
    if not data["source_exists"]:
        data["message"] = "Source checkout is gone, but the installed runtime is independent of it."
    if not runtime_ok:
        data["message"] = ("The installed runtime is incomplete; "
                           "run 'wob self repair' (or 'wob rescue' if wob cannot start).")
    elif not launcher_ok:
        data["message"] = "The launcher is missing, not executable, or points elsewhere; run 'wob self repair'."
    return data


def _verify_tree(app_dir: Path, files: dict, parallel: bool = True) -> dict:
    """Check manifest entries against the installed tree.

    Small installs (~60 files, ~0.5 MB) are faster to hash serially: spawning a
    thread pool costs more than the reads. The pool only pays for itself once
    there is real work, so the threshold is deliberate rather than "always
    parallel".
    """
    started = time.monotonic()
    missing = []
    modified = []
    unreadable = []
    checked = 0
    hashed_bytes = 0
    rels = sorted(files)

    def one(rel: str):
        meta = files.get(rel) or {}
        target = app_dir / rel
        try:
            stat_result = target.stat()
        except OSError:
            return rel, "missing", 0
        if not target.is_file():
            return rel, "missing", 0
        expected_size = meta.get("size", -1)
        if expected_size != stat_result.st_size:
            return rel, "modified", 0
        try:
            digest = _sha256_file(target)
        except OSError:
            return rel, "unreadable", stat_result.st_size
        if digest != meta.get("sha256"):
            return rel, "modified", stat_result.st_size
        return rel, "ok", stat_result.st_size

    total_bytes = sum(int((files.get(rel) or {}).get("size", 0) or 0) for rel in rels)
    use_pool = bool(parallel) and (len(rels) >= 64 or total_bytes >= 1_500_000)

    if not rels:
        results = []
    elif not use_pool:
        results = [one(rel) for rel in rels]
    else:
        from concurrent.futures import ThreadPoolExecutor

        workers = min(8, max(2, (os.cpu_count() or 2) * 2), len(rels))
        with ThreadPoolExecutor(max_workers=workers) as pool:
            results = list(pool.map(one, rels))

    for rel, verdict, size in results:
        if verdict == "ok":
            checked += 1
            hashed_bytes += size
        elif verdict == "modified":
            modified.append(rel)
        elif verdict == "unreadable":
            unreadable.append(rel)
        else:
            missing.append(rel)

    return {
        "checked": checked,
        "missing": missing,
        "modified": modified,
        "unreadable": unreadable,
        "hashed_bytes": hashed_bytes,
        "parallel": use_pool,
        "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
    }


def verify(install_root: Optional[Path] = None, parallel: bool = True,
           workers: Optional[int] = None) -> Dict[str, Any]:
    """Check installed files against the manifest hashes.

    Hashing runs on a small thread pool (``parallel=False`` forces serial
    verification for debugging). Results list every problem file, so callers
    can print more than the first handful.
    """
    started = time.monotonic()
    root = Path(install_root).expanduser().resolve() if install_root else default_install_root()
    manifest = _read_manifest(root)
    if not manifest:
        return {
            "ok": False,
            "error": "No install manifest found",
            "error_code": "installation_manifest_missing",
            "hint": "Install Wobble as software with: sh install.sh  (or: wob self install)",
            "install_root": str(root),
            "checked": 0,
            "file_count": 0,
            "missing": [],
            "modified": [],
            "unreadable": [],
            "launcher_ok": False,
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        }

    app_dir = Path(manifest.get("app_dir", root / APP_DIRNAME))
    files = manifest.get("files", {}) if isinstance(manifest.get("files"), dict) else {}
    report = _verify_tree(app_dir, files, parallel=parallel)

    if not files:
        return {
            "ok": False,
            "error": "Install manifest contains no file hashes.",
            "error_code": "installation_manifest_invalid",
            "hint": "Reinstall with: wob self install  (or: sh install.sh)",
            "install_root": str(root),
            "app_dir": str(app_dir),
            "checked": 0,
            "file_count": 0,
            "missing": [],
            "modified": [],
            "unreadable": [],
            "hashed_bytes": 0,
            "launcher_ok": False,
            "parallel": False,
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        }

    launcher = Path(manifest.get("launcher", default_bin_dir() / LAUNCHER_NAME))
    launcher_ok = _is_our_launcher(launcher)
    ok = not report["missing"] and not report["modified"] and not report["unreadable"] and launcher_ok
    data = {
        "ok": ok,
        "version": manifest.get("version"),
        "running_version": __version__,
        "checked": report["checked"],
        "file_count": len(files),
        "missing": report["missing"],
        "modified": report["modified"],
        "unreadable": report["unreadable"],
        "hashed_bytes": report["hashed_bytes"],
        "launcher_ok": launcher_ok,
        "install_root": str(root),
        "app_dir": str(app_dir),
        "parallel": report["parallel"],
        "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        "source_exists": bool(manifest.get("source") and Path(manifest["source"]).exists()),
    }
    if not ok:
        data["hint"] = (
            "Reinstall with: wob self install  (or: sh install.sh). "
            "Runtime files are never patched in place."
        )
    return data


def uninstall_legacy_symlink() -> Optional[str]:
    """Remove a pre-1.2 symlink launcher that points into a source checkout."""
    launcher = default_bin_dir() / LAUNCHER_NAME
    try:
        if launcher.is_symlink():
            target = os.readlink(str(launcher))
            if "wobble" in target:
                launcher.unlink()
                return target
    except OSError:
        return None
    return None
