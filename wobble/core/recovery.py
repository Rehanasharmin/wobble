# Manifest reconstruction
# ---------------------------------------------------------------------------
def rebuild_manifest(root: Path, app_dir: Path = None, manifest: dict = None,
                     version: str = None, source_kind: str = None,
                     trusted: dict = None, note: str = None) -> dict:
    """Regenerate ``install.json`` from what is actually on disk.

    This is what makes a corrupt or deleted manifest recoverable: the hashes
    are recomputed from the installed files, while ``trusted`` (the previous
    manifest or the snapshot) records how many of those files were independently
    verified. Nothing is claimed as verified that was not.
    """
    root = Path(root).expanduser().resolve() if root else installer.default_install_root()
    existing = manifest if manifest is not None else installer.read_manifest(root)
    app = Path(app_dir) if app_dir else (
        Path(existing["app_dir"]) if existing and existing.get("app_dir")
        else root / installer.APP_DIRNAME)
    if not app.is_dir():
        return {"ok": False, "error": f"runtime directory is missing: {app}",
                "error_code": "installation_runtime_missing"}

    files, total_bytes = _hash_tree(app)
    if not files:
        return {"ok": False, "error": f"no runtime files found under {app}",
                "error_code": "installation_runtime_empty"}

    trusted = trusted or {}
    unverified = [rel for rel, meta in files.items()
                  if trusted.get(rel, {}).get("sha256") not in (None, meta.get("sha256"))]
    # Files that were never part of a trusted tree are not blessed into the new
    # manifest: they stay visible as "unexpected runtime files" instead of being
    # silently legitimised by a repair.
    unexpected = sorted(rel for rel in files if rel not in trusted) if trusted else []
    if unexpected:
        for rel in unexpected:
            total_bytes -= int(files[rel].get("size", 0) or 0)
            files.pop(rel, None)

    launchers = []
    recorded = (existing or {}).get("launchers")
    if isinstance(recorded, list):
        launchers = [p for p in recorded if Path(p).is_file()]
    primary = (existing or {}).get("launcher") or str(
        installer.default_bin_dir() / installer.LAUNCHER_NAME)
    if not launchers and Path(primary).is_file():
        launchers = [primary]
    if not launchers:
        for candidate in installer._candidate_launchers():
            if candidate.is_file() and installer._is_our_launcher(candidate):
                launchers.append(str(candidate))
    if Path(primary).is_file() and str(primary) not in launchers:
        launchers.append(str(primary))

    completions = []
    for path in (existing or {}).get("completions") or []:
        if Path(path).is_file():
            completions.append(path)

    now = _iso_now()
    data = dict(existing or {})
    data.update({
        "schema": installer.INSTALL_SCHEMA,
        "name": "wobble",
        "version": version or (existing or {}).get("version")
        or tree_version(app) or __version__,
        "installed_at": (existing or {}).get("installed_at") or now,
        "install_root": str(root),
        "app_dir": str(app),
        "launcher": primary,
        "launchers": launchers,
        "completions": completions,
        "python": (existing or {}).get("python") or os.path.realpath(
            sys.executable or "python3"),
        "source": (existing or {}).get("source"),
        "standalone": True,
        "files": files,
        "file_count": len(files),
        "total_bytes": total_bytes,
        "manifest_rebuilt_at": now,
        "rebuilt_reason": note or "manifest reconstruction",
    })
    if source_kind:
        data["recovery_source"] = source_kind
    data.pop("verified_at", None)
    try:
        installer.atomic_write_json(installer.manifest_path(root), data)
    except OSError as exc:
        return {"ok": False, "error": f"could not write the manifest: {exc}",
                "error_code": "manifest_write_failed"}

    return {
        "ok": True,
        "path": str(installer.manifest_path(root)),
        "file_count": len(files),
        "total_bytes": total_bytes,
        "unverified": unverified[:20],
        "unverified_count": len(unverified),
        "unexpected": unexpected[:20],
        "unexpected_count": len(unexpected),
        "version": data["version"],
        "launchers": launchers,
    }


