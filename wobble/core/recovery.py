"""Wobble Recovery & Self-Healing
``wob self repair`` used to be honest but helpless: it could rewrite a launcher
or recompile bytecode, but a single corrupted runtime file left it saying
"reinstall", which is exactly the moment a reinstall is hardest — the checkout
may be gone, the network may be down, and ``wob`` itself may no longer start.

This module makes repair *actually repair*. It adds:

* a **verified offline snapshot** of the runtime, written at install time
  (``<root>/snapshot/app`` + ``snapshot.json`` with SHA-256 for every file),
  so a damaged install can be rebuilt without network or source checkout;
* an ordered **recovery-source ladder** — snapshot, then the recorded source
  checkout, then (explicitly opted in) a release tarball downloaded from
  GitHub — every candidate being version-checked and byte-compiled before it
  is trusted;
* **partial restore**: only files that are missing or fail their hash are
  replaced, and the damaged copies are preserved under ``repair-backups/``;
* **manifest reconstruction**, so a corrupt or deleted ``install.json`` no
  longer turns the installer amnesiac;
* **rescue assets** written outside the runtime (``rescue.py``, ``rescue.sh``,
  ``wob-rescue``) that can rebuild the application even when Python cannot
  import the damaged package at all.

Design rule that survives the change: integrity is never faked. Files are only
restored from a tree that matches the expected SHA-256 (or, when no hashes are
known at all, from a version-checked tree that compiles cleanly), never by
rewriting hashes over damaged bytes.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import time
from pathlib import Path

from wobble import __version__
from wobble.core import installer

SNAPSHOT_SCHEMA = 1
SNAPSHOT_DIRNAME = "snapshot"
SNAPSHOT_APP_DIRNAME = "app"
SNAPSHOT_MANIFEST_NAME = "snapshot.json"
BACKUP_DIRNAME = "repair-backups"
RESCUE_PY_NAME = "rescue.py"
RESCUE_SH_NAME = "rescue.sh"
RESCUE_LAUNCHER_NAME = "wob-rescue"
RESCUE_MARKER = "Wobble rescue launcher (auto-generated by `wob self install`)"

MAX_BACKUPS = 5
MAX_DOWNLOAD_BYTES = 32 * 1024 * 1024
MAX_ARCHIVE_FILES = 5000
MAX_ARCHIVE_BYTES = 64 * 1024 * 1024
DEFAULT_TIMEOUT = 30

# Files that must exist for a tree to be a usable Wobble runtime. ``wob.py`` is
# generated for source checkouts that never contained it.
REQUIRED_RUNTIME = (
    "wobble/__init__.py",
    "wobble/bootstrap.py",
    "wobble/cli.py",
)
GENERATED_BOOTSTRAP = "wob.py"

_IGNORED_DIRS = {"__pycache__", ".git", ".github", ".wobble"}


class RecoveryError(RuntimeError):
    """Raised when a recovery source cannot be used safely."""


# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
def snapshot_dir(root: Path) -> Path:
    return Path(root) / SNAPSHOT_DIRNAME


def snapshot_app_dir(root: Path) -> Path:
    return snapshot_dir(root) / SNAPSHOT_APP_DIRNAME


def snapshot_manifest_path(root: Path) -> Path:
    return snapshot_dir(root) / SNAPSHOT_MANIFEST_NAME


def backups_dir(root: Path) -> Path:
    return Path(root) / BACKUP_DIRNAME


def rescue_py_path(root: Path) -> Path:
    return Path(root) / RESCUE_PY_NAME


def rescue_sh_path(root: Path) -> Path:
    return Path(root) / RESCUE_SH_NAME


def rescue_command(root: Path) -> str:
    """The copy-paste command that works even when ``wob`` cannot start."""
    return f"sh {rescue_sh_path(root)}"


def _iso_now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _stamp() -> str:
    return time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())


# ---------------------------------------------------------------------------
# Tree helpers
# ---------------------------------------------------------------------------
def _hash_tree(root: Path) -> tuple:
    """Return ``(files, total_bytes)`` for the source files under *root*.

    Bytecode is deliberately excluded: it is always regenerated, and shipping
    stale ``.pyc`` files is how a repair ends up "succeeding" while Python keeps
    loading the old, broken module.
    """
    files = {}
    total = 0
    if not root.is_dir():
        return files, total
    for path in installer._iter_files(root):
        rel = path.relative_to(root).as_posix()
        try:
            size = path.stat().st_size
            digest = installer._sha256_file(path)
        except OSError:
            continue
        files[rel] = {"sha256": digest, "size": size}
        total += size
    return files, total


def tree_version(tree: Path) -> "str | None":
    """Read ``__version__`` from a Wobble source tree without importing it."""
    init = Path(tree) / "wobble" / "__init__.py"
    try:
        text = init.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return None
    match = re.search(r"__version__\s*=\s*[\"']([^\"']+)", text)
    return match.group(1) if match else None


def validate_tree(tree: Path, compile_check: bool = True) -> list:
    """Return a list of problems that make *tree* unusable as a runtime.

    Compiling every module is the cheapest possible proof that the candidate is
    not merely present but syntactically intact — exactly the failure mode a
    half-written copy produces.
    """
    tree = Path(tree)
    problems = []
    if not tree.is_dir():
        return [f"{tree} is not a directory"]
    for rel in REQUIRED_RUNTIME:
        if not (tree / rel).is_file():
            problems.append(f"missing {rel}")
    if problems:
        return problems
    if not compile_check:
        return problems
    for path in installer._iter_files(tree):
        if path.suffix != ".py":
            continue
        try:
            source = path.read_text(encoding="utf-8", errors="replace")
            compile(source, str(path), "exec")
        except (OSError, SyntaxError, ValueError) as exc:
            rel = path.relative_to(tree).as_posix()
            problems.append(f"{rel}: {type(exc).__name__}: {exc}")
            if len(problems) >= 5:
                break
    return problems


def _copy_tree_files(source: Path, destination: Path) -> list:
    """Copy source files (never bytecode) from *source* into *destination*."""
    copied = []
    for path in installer._iter_files(source):
        rel = path.relative_to(source)
        target = destination / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        copied.append(rel.as_posix())
    return copied


