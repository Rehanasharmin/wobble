def _backup_files(root: Path, app_dir: Path, rels, stamp: str = None) -> "tuple":
    """Copy damaged runtime files aside before they are overwritten.

    Returns ``(backup_dir, copied_rels, failed_rels)``. A failure is reported
    rather than swallowed: overwriting the only copy of a damaged file when the
    backup could not be written is exactly the data loss this step exists to
    prevent. The manifest is preserved here too, because after a rebuild it is
    the only record of what the install used to be.
    """
    stamp = stamp or _stamp()
    destination = backups_dir(root) / stamp
    copied = []
    failed = []
    for rel in rels:
        source = Path(app_dir) / rel
        if not source.is_file():
            continue
        target = destination / "app" / rel
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
            copied.append(rel)
        except OSError:
            failed.append(rel)
    manifest_file = Path(root) / installer.MANIFEST_NAME
    if manifest_file.is_file():
        try:
            destination.mkdir(parents=True, exist_ok=True)
            shutil.copy2(manifest_file, destination / installer.MANIFEST_NAME)
        except OSError:
            pass
    return destination, copied, failed


def _backup_tree(root: Path, app_dir: Path) -> "Path | None":
    """Move a whole (broken) runtime aside before a full reinstall.

    Moving inside the same filesystem is instant and keeps every byte of the
    damaged tree, which is what makes post-mortem debugging possible. Returns
    the backup stamp directory, or ``None`` when there was nothing to preserve;
    raises :class:`RecoveryError` when the tree exists but cannot be preserved.
    """
    if not Path(app_dir).exists():
        return None
    destination = backups_dir(root) / _stamp()
    try:
        destination.mkdir(parents=True, exist_ok=True)
        os.replace(Path(app_dir), destination / "app")
    except OSError as exc:
        shutil.rmtree(destination, ignore_errors=True)
        raise RecoveryError(
            f"could not preserve the damaged runtime in {destination}: {exc}"
        ) from exc
    manifest_file = Path(root) / installer.MANIFEST_NAME
    if manifest_file.is_file():
        try:
            shutil.copy2(manifest_file, destination / installer.MANIFEST_NAME)
        except OSError:
            pass
    return destination


def prune_backups(root: Path, keep: int = MAX_BACKUPS) -> list:
    """Keep only the most recent *keep* repair backups."""
    base = backups_dir(root)
    removed = []
    if not base.is_dir():
        return removed
    entries = sorted((p for p in base.iterdir() if p.is_dir()), reverse=True)
    for entry in entries[max(1, keep):]:
        shutil.rmtree(entry, ignore_errors=True)
        if not entry.exists():
            removed.append(str(entry))
    return removed


def _atomic_copy(source: Path, target: Path) -> None:
    """Replace *target* with *source* without ever leaving a partial file."""
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary = target.with_name(f".{target.name}.wobble-new")
    shutil.copy2(source, temporary)
    if os.access(str(source), os.X_OK):
        try:
            temporary.chmod(0o755)
        except OSError:
            pass
    os.replace(temporary, target)


def restore_runtime(root: Path, manifest: dict = None, app_dir: Path = None,
                    bin_dir: Path = None, prefer: str = "auto", dry_run: bool = False,
                    backup: bool = True, network: bool = False, url: str = None,
                    allow_version_drift: bool = False,
                    timeout: float = DEFAULT_TIMEOUT) -> dict:
    """Rebuild missing or corrupted runtime files from a trusted source.

    Two modes are handled transparently:

    * **partial** — the app directory is intact enough to start Wobble, so only
      the files that fail their size/SHA-256 check are replaced;
    * **full** — the runtime (or the manifest) is gone, so the whole
      application is reinstalled from the selected tree using the normal
      installer path, then re-snapshotted.
    """
    started = time.monotonic()
    root = Path(root).expanduser().resolve() if root else installer.default_install_root()
    app, _app_warning = resolve_app_dir(root, manifest, app_dir)
    snapshot_manifest, _snapshot_error = read_snapshot_manifest(root)
    expected = expected_files(manifest, snapshot_manifest)

    report = {
        "app_dir_warning": _app_warning,
        "success": False,
        "mode": None,
        "root": str(root),
        "app_dir": str(app),
        "dry_run": bool(dry_run),
        "source": None,
        "missing": [],
        "modified": [],
        "restored": [],
        "preserved": [],
        "backup_dir": None,
        "manifest_rebuilt": False,
        "verification": None,
        "error": None,
        "error_code": None,
        "fix": None,
        "elapsed_ms": 0.0,
    }

    state = assess(app, expected) if expected else None
    app_ok = runtime_present(app)
    report["assessment"] = state

    if state and state["healthy"] and app_ok:
        report.update({"success": True, "mode": "none",
                       "elapsed_ms": round((time.monotonic() - started) * 1000, 1)})
        return report

    if not app_ok or not expected or not state:
        # Full recovery: the runtime itself is gone, so copy a whole tree.
        return _restore_full(root, app, bin_dir, manifest, prefer=prefer,
                             dry_run=dry_run, network=network, url=url,
                             allow_version_drift=allow_version_drift,
                             started=started, report=report, timeout=timeout)

    report["missing"] = state["missing"]
    report["modified"] = state["modified"]
    damaged = list(state["damaged"])
    try:
        source = select_source(
            root, manifest, prefer=prefer, network=network, url=url,
            allow_version_drift=allow_version_drift,
            target_version=(manifest or {}).get("version"),
            timeout=timeout, exclude=app,
        )
    except RecoveryError as exc:
        report.update({
            "error": str(exc),
            "error_code": "recovery_source_unavailable",
            "fix": ("wob self repair --emergency --from network   "
                    "(or reinstall: sh install.sh)"),
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        return report

    report["source"] = _public_source(source)
    source_files = source.get("files") or {}
    source_tree = Path(source["path"])

    restorable, unavailable = [], []
    for rel in damaged:
        if rel in source_files or (source_tree / rel).is_file():
            restorable.append(rel)
        elif rel == GENERATED_BOOTSTRAP:
            restorable.append(rel)
        else:
            unavailable.append(rel)

    if dry_run:
        if source.get("_staging"):
            shutil.rmtree(source["_staging"], ignore_errors=True)
        report.update({
            "success": True,
            "mode": "partial",
            "restored": restorable,
            "unavailable": unavailable,
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        report["plan"] = {
            "restore": restorable,
            "unavailable": unavailable,
            "source": _public_source(source),
            "backup": bool(backup),
        }
        if unavailable:
            report["warnings"] = [f"{len(unavailable)} file(s) are absent from the recovery source"]
        return report

    if backup:
        try:
            backup_dir, preserved, backup_failed = _backup_files(root, app, damaged)
        except OSError as exc:
            backup_dir, preserved, backup_failed = None, [], damaged
        if backup_failed:
            report.update({
                "error": ("Could not preserve the damaged files before restoring them "
                          f"({len(backup_failed)} file(s)); nothing was changed. "
                          "Check free space and permissions on "
                          f"{backups_dir(root)}."),
                "error_code": "recovery_backup_failed",
                "failed_to_preserve": backup_failed[:20],
                "fix": f"chmod -R u+rwX {backups_dir(root)}   (or re-run with --no-backup)",
                "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
            })
            return report
        report["backup_dir"] = str(backup_dir) if preserved else None
        report["preserved"] = preserved

    restored, failed = [], []
    try:
        for rel in restorable:
            target = app / rel
            try:
                if rel == GENERATED_BOOTSTRAP and not (source_tree / rel).is_file():
                    target.parent.mkdir(parents=True, exist_ok=True)
                    installer.atomic_write_text(target, installer._BOOTSTRAP)
                    target.chmod(0o755)
                else:
                    _atomic_copy(source_tree / rel, target)
                restored.append(rel)
            except OSError as exc:
                failed.append({"file": rel, "error": str(exc)})
    finally:
        if source.get("_staging"):
            shutil.rmtree(source["_staging"], ignore_errors=True)

    # Re-check every restored file against what the install expects.
    mismatched = []
    for rel in restored:
        verdict = _file_verdict(app / rel, expected.get(rel) or source_files.get(rel))
        if verdict != "ok":
            mismatched.append(rel)

    # Only re-baseline the manifest when the restore was complete: rewriting it
    # while files are still missing would quietly drop them from future checks
    # and make the damage invisible.
    if failed or unavailable:
        manifest_result = {
            "ok": False,
            "skipped": True,
            "error": "manifest not rebuilt while runtime files are still missing",
        }
    else:
        manifest_result = rebuild_manifest(
            root, app_dir=app, manifest=manifest,
            version=(manifest or {}).get("version") or source.get("version"),
            source_kind=source.get("kind"),
            trusted=expected,
            note=f"restored {len(restored)} file(s) from {source.get('kind')}",
        )
    report["manifest_rebuilt"] = bool(manifest_result.get("ok"))
    report["manifest"] = manifest_result

    verification = installer.verify(root)
    report["verification"] = verification
    report["restored"] = restored
    report["failed"] = failed
    report["unavailable"] = unavailable
    report["mismatched"] = mismatched
    report["mode"] = "partial"

    leftover_problems = list(mismatched) + list(unavailable)
    if failed:
        report["error"] = f"{len(failed)} file(s) could not be written"
        report["error_code"] = "recovery_write_failed"
        report["fix"] = f"Check permissions on {app} and re-run 'wob self repair'"
    elif leftover_problems:
        report["error"] = (
            f"restored from {source.get('kind')} but {len(leftover_problems)} file(s) "
            "still do not match the manifest"
        )
        report["error_code"] = "recovery_incomplete"
        report["fix"] = "wob self repair --emergency --from network"
    else:
        report["success"] = bool(verification.get("ok") and manifest_result.get("ok"))

    report["elapsed_ms"] = round((time.monotonic() - started) * 1000, 1)
    return report


def _restore_full(root: Path, app: Path, bin_dir: Path, manifest: dict,
                  prefer: str, dry_run: bool, network: bool, url: str,
                  allow_version_drift: bool, started: float, report: dict,
                  timeout: float = DEFAULT_TIMEOUT) -> dict:
    """Reinstall the whole runtime from the best available tree."""
    try:
        source = select_source(
            root, manifest, prefer=prefer, network=network, url=url,
            allow_version_drift=allow_version_drift,
            target_version=(manifest or {}).get("version"),
            timeout=timeout, exclude=app,
        )
    except RecoveryError as exc:
        report.update({
            "mode": "full",
            "error": str(exc),
            "error_code": "recovery_source_unavailable",
            "fix": ("Restore it from the source checkout (sh install.sh), "
                    f"or run: {rescue_command(root)}"),
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        return report

    report["mode"] = "full"
    report["source"] = _public_source(source)
    if dry_run:
        if source.get("_staging"):
            shutil.rmtree(source["_staging"], ignore_errors=True)
        report.update({
            "success": True,
            "restored": [],
            "plan": {"reinstall_from": _public_source(source),
                     "app_dir": str(app)},
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        return report

    try:
        backup_dir = _backup_tree(root, app)
    except RecoveryError as exc:
        report.update({
            "mode": "full",
            "error": str(exc),
            "error_code": "recovery_backup_failed",
            "fix": f"chmod -R u+rwX {backups_dir(root)}   (or re-run with --no-backup)",
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        return report
    if backup_dir:
        report["backup_dir"] = str(backup_dir)
    else:
        report["preserved"] = []

    try:
        result = installer.install(
            source_root=Path(source["path"]),
            install_root=root,
            bin_dir=Path(bin_dir) if bin_dir else None,
            force=False,
            completions=True,
            update_path=False,
        )
    except Exception as exc:  # InstallerError or OSError
        if source.get("_staging"):
            shutil.rmtree(source["_staging"], ignore_errors=True)
        # Put the preserved runtime back rather than leaving the user with
        # nothing at all because a reinstall attempt failed.
        if backup_dir and (backup_dir / "app").exists() and not app.exists():
            try:
                os.replace(backup_dir / "app", app)
                report["restored_previous"] = True
            except OSError:
                report["restored_previous"] = False
        report.update({
            "error": f"full recovery failed: {exc}",
            "error_code": "recovery_install_failed",
            "fix": f"Run: {rescue_command(root)}",
            "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
        })
        return report
    finally:
        if source.get("_staging"):
            shutil.rmtree(source["_staging"], ignore_errors=True)

    report.update({
        "success": True,
        "restored": sorted((result.get("files") or {}).keys()),
        "backup_dir": str(backup_dir) if backup_dir else None,
        "manifest_rebuilt": True,
        "version": result.get("version"),
        "file_count": result.get("file_count"),
        "verification": installer.verify(root),
        "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
    })
    return report


def _public_source(source: dict) -> dict:
    if not source:
        return {}
    return {key: source.get(key) for key in
            ("kind", "path", "version", "matches_install", "detail", "url")
            if source.get(key) is not None}


