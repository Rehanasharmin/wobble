def read_snapshot_manifest(root: Path):
    """Return ``(data, error)`` for the snapshot manifest; never raises."""
    path = snapshot_manifest_path(root)
    if not path.is_file():
        return None, "snapshot manifest not found"
    try:
        with open(path, "r", encoding="utf-8") as handle:
            data = json.load(handle)
    except (OSError, ValueError) as exc:
        return None, str(exc)
    if not isinstance(data, dict):
        return None, "snapshot manifest is not a JSON object"
    files = data.get("files")
    if not isinstance(files, dict) or not files:
        return None, "snapshot manifest contains no file hashes"
    return data, None


def describe_snapshot(root: Path) -> dict:
    """Cheap metadata-only view used by ``wob self status`` and the doctor."""
    path = snapshot_dir(root)
    manifest, error = read_snapshot_manifest(root)
    app = snapshot_app_dir(root)
    present = path.is_dir()
    data = {
        "present": present,
        "valid": False,
        "path": str(path),
        "app": str(app),
        "exists_on_disk": app.is_dir() and (app / GENERATED_BOOTSTRAP).is_file(),
        "version": None,
        "created_at": None,
        "file_count": 0,
        "total_bytes": 0,
        "error": error,
        "rescue_python": rescue_py_path(root).is_file(),
        "rescue_shell": rescue_sh_path(root).is_file(),
    }
    if manifest:
        data.update({
            "valid": True,
            "version": manifest.get("version"),
            "created_at": manifest.get("created_at"),
            "file_count": len(manifest.get("files") or {}),
            "total_bytes": int(manifest.get("total_bytes", 0) or 0),
            "source": manifest.get("source"),
            "error": None,
        })
        if not data["exists_on_disk"]:
            data["valid"] = False
            data["error"] = "snapshot manifest exists but the snapshot tree is missing"
    return data


def create_snapshot(root: Path, app_dir: Path = None, version: str = None,
                    trusted_files: dict = None, source: str = "runtime",
                    force: bool = False) -> dict:
    """Write a verified copy of the runtime to ``<root>/snapshot``.

    ``trusted_files`` (a ``{rel: {sha256,size}}`` map, usually the install
    manifest) is the integrity gate: with it, the snapshot is only written when
    every file still matches, so a snapshot can never bless damaged bytes. Set
    ``force`` to snapshot the current tree regardless (used by ``--accept-current``
    where the local tree *is* the new truth).
    """
    started = time.monotonic()
    root = Path(root).expanduser().resolve() if root else installer.default_install_root()
    app = Path(app_dir) if app_dir else root / installer.APP_DIRNAME

    problems = validate_tree(app, compile_check=False)
    if problems:
        raise RecoveryError("cannot snapshot a damaged runtime: " + "; ".join(problems))
    if not (app / GENERATED_BOOTSTRAP).is_file():
        raise RecoveryError(f"cannot snapshot a runtime without {GENERATED_BOOTSTRAP}")

    if trusted_files and not force:
        unverified = [rel for rel, meta in trusted_files.items()
                      if _file_verdict(app / rel, meta) != "ok"]
        if unverified:
            raise RecoveryError(
                "refusing to snapshot a runtime that does not match its manifest "
                f"({len(unverified)} file(s) differ); run 'wob self repair' first"
            )

    staging = root / f".snapshot.tmp-{os.getpid()}"
    if staging.exists():
        shutil.rmtree(staging, ignore_errors=True)
    try:
        staging_app = staging / SNAPSHOT_APP_DIRNAME
        staging_app.mkdir(parents=True, exist_ok=True)
        _copy_tree_files(app, staging_app)
        files, total_bytes = _hash_tree(staging_app)
        manifest = {
            "schema": SNAPSHOT_SCHEMA,
            "name": "wobble",
            "version": version or tree_version(app) or __version__,
            "created_at": _iso_now(),
            "source": source,
            "files": files,
            "file_count": len(files),
            "total_bytes": total_bytes,
        }
        with open(staging / SNAPSHOT_MANIFEST_NAME, "w", encoding="utf-8") as handle:
            json.dump(manifest, handle, indent=2)
            handle.write("\n")

        target = snapshot_dir(root)
        previous = root / ".snapshot.old"
        if previous.exists():
            shutil.rmtree(previous, ignore_errors=True)
        if target.exists():
            os.replace(target, previous)
        try:
            os.replace(staging, target)
        except Exception:
            if not target.exists() and previous.exists():
                os.replace(previous, target)
            raise
        finally:
            shutil.rmtree(previous, ignore_errors=True)
    finally:
        shutil.rmtree(staging, ignore_errors=True)

    return {
        "ok": True,
        "path": str(snapshot_dir(root)),
        "app": str(snapshot_app_dir(root)),
        "version": manifest["version"],
        "file_count": manifest["file_count"],
        "total_bytes": manifest["total_bytes"],
        "created_at": manifest["created_at"],
        "elapsed_ms": round((time.monotonic() - started) * 1000, 1),
    }


def verify_snapshot(root: Path, deep: bool = True) -> dict:
    """Verify the offline snapshot against its own manifest."""
    started = time.monotonic()
    manifest, error = read_snapshot_manifest(root)
    result = {
        "ok": False,
        "present": snapshot_dir(root).is_dir(),
        "path": str(snapshot_dir(root)),
        "error": error,
        "version": None,
        "created_at": None,
        "checked": 0,
        "file_count": 0,
        "missing": [],
        "modified": [],
        "elapsed_ms": 0.0,
    }
    if not manifest:
        result["elapsed_ms"] = round((time.monotonic() - started) * 1000, 1)
        return result

    app = snapshot_app_dir(root)
    files = manifest.get("files") or {}
    result.update({
        "version": manifest.get("version"),
        "created_at": manifest.get("created_at"),
        "file_count": len(files),
    })
    for rel, meta in sorted(files.items()):
        verdict = _file_verdict(app / rel, meta, deep=deep)
        if verdict == "ok":
            result["checked"] += 1
        elif verdict == "missing":
            result["missing"].append(rel)
        elif verdict == "modified":
            result["modified"].append(rel)
    result["ok"] = not result["missing"] and not result["modified"]
    if not result["ok"] and not result["error"]:
        result["error"] = (f"{len(result['missing'])} missing, "
                           f"{len(result['modified'])} modified")
    result["elapsed_ms"] = round((time.monotonic() - started) * 1000, 1)
    return result


# ---------------------------------------------------------------------------
# Damage assessment
# ---------------------------------------------------------------------------
def _file_verdict(path: Path, meta: dict = None, deep: bool = True) -> str:
    """Classify *path* as ``ok``, ``missing``, ``modified`` or ``unreadable``."""
    try:
        stat_result = path.stat()
    except OSError:
        return "missing"
    if not path.is_file():
        return "missing"
    meta = meta or {}
    expected_size = meta.get("size")
    if expected_size is not None and int(expected_size) != stat_result.st_size:
        return "modified"
    expected_hash = meta.get("sha256")
    if deep and expected_hash:
        try:
            if installer._sha256_file(path) != expected_hash:
                return "modified"
        except OSError:
            return "unreadable"
    return "ok"


def expected_files(manifest: dict = None, snapshot: dict = None) -> dict:
    """Merge the install manifest and snapshot hash maps into one expectation.

    The install manifest wins when both describe the same path: it is the
    contract this particular installation was verified against.
    """
    files = {}
    snapshot_files = (snapshot or {}).get("files")
    if isinstance(snapshot_files, dict):
        files.update(snapshot_files)
    manifest_files = (manifest or {}).get("files")
    if isinstance(manifest_files, dict):
        files.update(manifest_files)
    return files


def assess(app_dir: Path, expected: dict = None) -> dict:
    """Compare the installed runtime against *expected* hashes."""
    expected = expected or {}
    missing, modified, unreadable = [], [], []
    ok = 0
    for rel, meta in sorted(expected.items()):
        verdict = _file_verdict(Path(app_dir) / rel, meta)
        if verdict == "ok":
            ok += 1
        elif verdict == "missing":
            missing.append(rel)
        elif verdict == "unreadable":
            unreadable.append(rel)
        else:
            modified.append(rel)
    return {
        "checked": ok + len(missing) + len(modified) + len(unreadable),
        "ok": ok,
        "missing": missing,
        "modified": modified,
        "unreadable": unreadable,
        "damaged": missing + modified + unreadable,
        "healthy": not (missing or modified or unreadable),
    }


def resolve_app_dir(root: Path, manifest: dict = None,
                    app_dir: Path = None) -> "tuple":
    """Return ``(app_dir, warning)`` for a manifest that may be corrupted.

    ``install.json`` is one of the files that can be damaged, and it carries the
    path repair writes into. A tampered or truncated manifest must never be able
    to aim a restore at a directory outside the install root, so an out-of-root
    ``app_dir`` is ignored in favour of the standard ``<root>/app``.
    """
    root = Path(root)
    default = root / installer.APP_DIRNAME
    candidate = Path(app_dir) if app_dir else None
    if candidate is None:
        recorded = (manifest or {}).get("app_dir")
        candidate = Path(recorded) if recorded else default
    try:
        root_resolved = root.resolve()
        candidate_resolved = candidate.resolve()
        relative = candidate_resolved.relative_to(root_resolved)
    except (OSError, ValueError):
        return default, (f"manifest app_dir '{candidate}' is outside {root}; "
                         "using the default app directory")
    if str(relative) in ("", "."):
        return default, (f"manifest app_dir '{candidate}' is the install root itself; "
                         "using the default app directory")
    return candidate, None


def runtime_present(app_dir: Path) -> bool:
    """True when the minimum needed to start ``wob`` exists."""
    return bool(
        Path(app_dir).is_dir()
        and (Path(app_dir) / GENERATED_BOOTSTRAP).is_file()
        and (Path(app_dir) / "wobble" / "cli.py").is_file()
    )


