# Recovery sources
# ---------------------------------------------------------------------------
def _source_descriptor(kind: str, tree: Path, version: str = None,
                       files: dict = None, expected: dict = None,
                       detail: str = "") -> dict:
    tree = Path(tree)
    if files is None:
        files, _total = _hash_tree(tree)
    matches = 0
    if expected:
        for rel, meta in files.items():
            want = expected.get(rel)
            if want and want.get("sha256") and want.get("sha256") == meta.get("sha256"):
                matches += 1
    return {
        "kind": kind,
        "path": str(tree),
        "version": version if version is not None else tree_version(tree),
        "files": files,
        "matches_install": matches,
        "detail": detail,
    }


def _snapshot_source(root: Path, expected: dict) -> "dict | None":
    manifest, _error = read_snapshot_manifest(root)
    if not manifest:
        return None
    app = snapshot_app_dir(root)
    if not (app / GENERATED_BOOTSTRAP).is_file():
        return None
    # Never repair from a snapshot that is itself damaged: that would just move
    # the corruption around and report success.
    verification = verify_snapshot(root, deep=True)
    if not verification.get("ok"):
        raise RecoveryError(
            "the offline snapshot is damaged "
            f"({len(verification.get('missing', []))} missing, "
            f"{len(verification.get('modified', []))} modified)"
        )
    return _source_descriptor(
        "snapshot", app,
        version=manifest.get("version"),
        files=manifest.get("files") or {},
        expected=expected,
        detail=f"offline snapshot created {manifest.get('created_at')}",
    )


def _checkout_source(manifest: dict, expected: dict, exclude: Path = None) -> "dict | None":
    """Use the checkout Wobble was installed from, if it still exists."""
    excluded = None
    if exclude:
        try:
            excluded = str(Path(exclude).resolve())
        except OSError:
            excluded = str(exclude)
    candidates = []
    recorded = (manifest or {}).get("source")
    if recorded:
        candidates.append(Path(recorded))
    # When running from a source checkout, package_root() *is* a valid tree.
    try:
        candidates.append(installer.package_root())
    except Exception:  # pragma: no cover - defensive
        pass
    seen = set()
    for candidate in candidates:
        candidate = Path(candidate)
        try:
            key = str(candidate.resolve())
        except OSError:
            continue
        if key in seen or not candidate.is_dir():
            continue
        seen.add(key)
        if excluded and key == excluded:
            continue
        if validate_tree(candidate):
            continue
        return _source_descriptor(
            "source", candidate, expected=expected,
            detail="the source checkout this installation came from",
        )
    return None


def _default_urls(version: str = None) -> list:
    base = "https://codeload.github.com/Rehanasharmin/wobble/tar.gz"
    urls = []
    if version:
        urls.append(f"{base}/refs/tags/v{version}")
    urls.append(f"{base}/refs/heads/main")
    return urls


def _download(url: str, timeout: float = DEFAULT_TIMEOUT) -> Path:
    """Fetch *url* into a temporary file, refusing oversized responses."""
    import tempfile
    import urllib.error
    import urllib.request

    handle, name = tempfile.mkstemp(prefix="wobble_dl_", suffix=".tar.gz")
    os.close(handle)
    target = Path(name)
    request = urllib.request.Request(
        url, headers={"User-Agent": f"wobble-rescue/{__version__}"})
    received = 0
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            with open(target, "wb") as out:
                while True:
                    chunk = response.read(64 * 1024)
                    if not chunk:
                        break
                    received += len(chunk)
                    if received > MAX_DOWNLOAD_BYTES:
                        raise RecoveryError(
                            f"download exceeded {MAX_DOWNLOAD_BYTES // (1024 * 1024)} MB")
                    out.write(chunk)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        target.unlink(missing_ok=True)
        raise RecoveryError(f"download failed: {exc}") from exc
    except Exception:
        target.unlink(missing_ok=True)
        raise
    if received == 0:
        target.unlink(missing_ok=True)
        raise RecoveryError("download returned an empty archive")
    return target


def _extract_archive(archive: Path, destination: Path) -> Path:
    """Safely extract a Wobble tarball and return the tree it contains.

    Extraction is manual rather than ``tarfile.extractall``: no absolute paths,
    no ``..`` components, no symlinks, no device nodes, and hard caps on the
    number and size of files. A rescue tool that can be pointed at a URL must
    never be trickable into writing outside its staging directory.
    """
    import tarfile

    destination = Path(destination)
    destination.mkdir(parents=True, exist_ok=True)
    count = 0
    total = 0
    with tarfile.open(archive, "r:*") as tar:
        for member in tar.getmembers():
            if count >= MAX_ARCHIVE_FILES:
                raise RecoveryError("archive contains too many files")
            name = member.name.replace("\\", "/")
            parts = [part for part in name.split("/") if part not in ("", ".")]
            if not parts or name.startswith("/") or ".." in parts:
                continue
            if member.issym() or member.islnk() or member.isdev():
                continue
            if not member.isfile():
                continue
            if "__pycache__" in parts or parts[-1].endswith((".pyc", ".pyo")):
                continue
            if member.size > MAX_ARCHIVE_BYTES:
                raise RecoveryError("archive contains an oversized file")
            total += member.size
            if total > MAX_ARCHIVE_BYTES:
                raise RecoveryError("archive exceeds the extraction size limit")
            target = destination.joinpath(*parts)
            try:
                target.relative_to(destination)
            except ValueError:
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            source = tar.extractfile(member)
            if source is None:
                continue
            with source, open(target, "wb") as out:
                shutil.copyfileobj(source, out)
            count += 1

    return _find_source_tree(destination)


def _find_source_tree(root: Path) -> Path:
    """Locate the Wobble package root inside an extracted archive."""
    root = Path(root)
    if validate_tree(root, compile_check=False) == []:
        return root
    candidates = []
    if root.is_dir():
        for child in sorted(root.iterdir()):
            if child.is_dir() and validate_tree(child, compile_check=False) == []:
                candidates.append(child)
    if not candidates:
        raise RecoveryError("downloaded archive does not contain a Wobble runtime")
    return candidates[0]


def _network_source(version: str, expected: dict, url: str = None,
                    timeout: float = DEFAULT_TIMEOUT) -> dict:
    urls = [url] if url else _default_urls(version)
    errors = []
    for candidate in urls:
        archive = None
        staging = Path(os.environ.get("TMPDIR") or "/tmp") / f"wobble-fetch-{os.getpid()}"
        try:
            archive = _download(candidate, timeout=timeout)
            if staging.exists():
                shutil.rmtree(staging, ignore_errors=True)
            tree = _extract_archive(archive, staging)
            problems = validate_tree(tree)
            if problems:
                raise RecoveryError("; ".join(problems))
            descriptor = _source_descriptor(
                "network", tree, expected=expected,
                detail=f"downloaded from {candidate}",
            )
            descriptor["url"] = candidate
            descriptor["_staging"] = str(staging)
            return descriptor
        except (RecoveryError, OSError, ValueError) as exc:
            errors.append(f"{candidate}: {exc}")
        finally:
            if archive is not None:
                try:
                    Path(archive).unlink()
                except OSError:
                    pass
    raise RecoveryError("no usable download: " + " | ".join(errors[:3]))


def select_source(root: Path, manifest: dict = None, prefer: str = "auto",
                  network: bool = False, url: str = None,
                  allow_version_drift: bool = False,
                  target_version: str = None, timeout: float = DEFAULT_TIMEOUT,
                  exclude: Path = None) -> dict:
    """Choose the best trusted tree to repair from.

    Returns a descriptor with ``kind`` (``snapshot``/``source``/``network``),
    ``path``, ``files``, ``version`` and ``detail``. Raises
    :class:`RecoveryError` with an actionable message when nothing usable is
    available, because "no source" is precisely the situation the user must be
    told about explicitly.
    """
    root = Path(root).expanduser().resolve() if root else installer.default_install_root()
    expected = expected_files(manifest)
    target_version = target_version or (manifest or {}).get("version")
    notes = []
    tried = []
    # The damaged runtime is never a recovery source, even when a caller forgets
    # to say so: copying a broken tree over itself would "succeed" while fixing
    # nothing.
    exclude = Path(exclude) if exclude else Path(root) / installer.APP_DIRNAME
    try:
        excluded = str(exclude.resolve())
    except OSError:
        excluded = str(exclude)

    prefer = (prefer or "auto").lower()
    if prefer not in ("auto", "snapshot", "source", "network"):
        raise RecoveryError(f"unknown recovery source '{prefer}' (use auto, snapshot, source or network)")

    order = []
    if prefer in ("auto", "snapshot"):
        order.append("snapshot")
    if prefer in ("auto", "source"):
        order.append("source")
    if prefer == "network" or (prefer == "auto" and (network or url)):
        order.append("network")

    for kind in order:
        candidate = None
        try:
            if kind == "snapshot":
                candidate = _snapshot_source(root, expected)
                if candidate is None:
                    tried.append("snapshot: not available")
            elif kind == "source":
                candidate = _checkout_source(manifest, expected, exclude=exclude)
                if candidate is None:
                    tried.append("source checkout: not available")
            elif kind == "network":
                version = target_version or __version__
                candidate = _network_source(version, expected, url=url, timeout=timeout)
                notes.append("downloaded a release archive from GitHub")
        except RecoveryError as exc:
            tried.append(f"{kind}: {exc}")
            continue
        if candidate is None:
            continue
        if excluded:
            try:
                same = str(Path(candidate["path"]).resolve()) == excluded
            except OSError:
                same = str(candidate["path"]) == excluded
            if same:
                tried.append(f"{kind}: points at the damaged runtime itself")
                if candidate.get("_staging"):
                    shutil.rmtree(candidate["_staging"], ignore_errors=True)
                continue

        source_version = candidate.get("version")
        if (target_version and source_version and source_version != target_version
                and not allow_version_drift):
            tried.append(
                f"{kind}: version {source_version} does not match the installed "
                f"{target_version} (use --emergency to accept a version change)"
            )
            if candidate.get("_staging"):
                shutil.rmtree(candidate["_staging"], ignore_errors=True)
            continue

        candidate["notes"] = notes
        candidate["tried"] = tried
        return candidate

    raise RecoveryError(
        "No verified recovery source is available. " + "; ".join(tried or ["none found"])
    )


